(* The bytecode of a standalone OUT.wasm, as C arrays.

   Without the JavaScript glue there is no file system to ship the bytecode
   in.  Its sections become the arrays of a generated bytecode.c (with
   #embed), and share/runtime/main.c starts the program with
   caml_startup_code, as the C file of `ocamlc -output-obj` does:
   - CODE and DATA as they are,
   - the section table, for the toplevel and Dynlink: what the
     -output-obj file of the same compiler holds (bytecomp/bytelink.ml), a
     marshalled association of SYMB and CRCS (and PRIM before 5.0) to the
     values of those sections,
   - the debug events of DBUG, which the runtime would read from the
     executable file: relocated and gathered in one marshalled array here,
     what read_main_debug_info builds from DBUG (see the `ocaml` recipe). *)

let section_table ~ocaml_major bc =
  let get name = Option.value (Bytecode.section bc name) ~default:"" in
  let marshalled name : Obj.t = match get name with "" -> Obj.repr 0 | s -> Marshal.from_string s 0 in
  if ocaml_major >= 5 then
    Marshal.to_string ([| ("SYMB", marshalled "SYMB"); ("CRCS", marshalled "CRCS") |] : (string * Obj.t) array) []
  else
    Marshal.to_string
      ([ ("SYMB", marshalled "SYMB"); ("PRIM", Obj.repr (get "PRIM")); ("CRCS", marshalled "CRCS") ] : (string * Obj.t) list)
      []

(* DBUG: a count, then for each compilation unit its code offset, its list
   of debug events (whose first field, ev_pos, is relative to that offset)
   and a list of directories. *)
let debug_events bc =
  match Bytecode.section bc "DBUG" with
  | None | Some "" -> None
  | Some s ->
      let n = Bytecode.int32_be s 0 in
      let pos = ref 4 in
      let units =
        Array.init n (fun _ ->
            let orig = Bytecode.int32_be s !pos in
            pos := !pos + 4;
            let evl : Obj.t = Marshal.from_string s !pos in
            let skip () = pos := !pos + Marshal.total_size (Bytes.unsafe_of_string s) !pos in
            skip ();
            skip ();
            let rec relocate l =
              if Obj.is_block l then (
                let ev = Obj.field l 0 in
                Obj.set_field ev 0 (Obj.repr ((Obj.obj (Obj.field ev 0) : int) + orig));
                relocate (Obj.field l 1))
            in
            relocate evl;
            evl)
      in
      Some (Marshal.to_string units [])

(* Writes bytecode.c and the files it embeds in DIR; returns bytecode.c. *)
let write ~ocaml_major ~dir bc =
  let file name contents = Compat.write_file (Filename.concat dir name) contents in
  let b = Buffer.create 2048 in
  let pr fmt = Printf.bprintf b fmt in
  pr "/* Generated by ocaml-emcc: the bytecode, linked in as data (share/runtime/main.c). */\n";
  pr "#include <stddef.h>\n";
  let array ?(attr = "") name ~ctype contents =
    file (name ^ ".bin") contents;
    if contents = "" then pr "\n%s ocaml_emcc_%s[1]%s;\n" ctype name attr
    else pr "\n%s ocaml_emcc_%s[]%s = {\n#embed \"%s.bin\"\n};\n" ctype name attr name;
    pr "const size_t ocaml_emcc_%s_size = %d;\n" name (String.length contents)
  in
  let get name = Option.value (Bytecode.section bc name) ~default:"" in
  (* threaded in place by the runtime: writable, aligned as code_t *)
  array "code" ~ctype:"unsigned char" ~attr:" __attribute__((aligned(8)))" (get "CODE");
  array "data" ~ctype:"char" (get "DATA");
  array "sections" ~ctype:"char" (section_table ~ocaml_major bc);
  (match debug_events bc with
  | Some ev ->
      array "debug" ~ctype:"char" ev;
      pr "char *const ocaml_emcc_debug_events = ocaml_emcc_debug;\n";
      pr "const size_t ocaml_emcc_debug_events_size = %d;\n" (String.length ev)
  | None ->
      pr "\nchar *const ocaml_emcc_debug_events = NULL;\n";
      pr "const size_t ocaml_emcc_debug_events_size = 0;\n");
  let c = Filename.concat dir "bytecode.c" in
  Compat.write_file c (Buffer.contents b);
  c
