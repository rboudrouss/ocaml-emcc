(* The C libraries a .cma names (-cclib -lX, -dllib -lX: its stubs, the
   libraries they use), as ocamlobjinfo reports them. *)
let cma_c_libs input =
  if not (Filename.check_suffix input ".cma") then []
  else
    match Env.output_of (Filename.concat (Env.host_bin ()) "ocamlobjinfo") [ input ] with
    | None -> []
    | Some out ->
        let fields = [ "Extra C object files:"; "Extra C options:"; "Extra dynamically-loaded libraries:" ] in
        String.split_on_char '\n' out
        |> Compat.concat_map (fun l ->
               match List.find_opt (fun f -> Str_util.starts_with ~prefix:f l) fields with
               | None -> []
               | Some f -> Str_util.words (String.sub l (String.length f) (String.length l - String.length f)))
        |> List.filter_map (fun w ->
               if Str_util.starts_with ~prefix:"-l" w then Some (String.sub w 2 (String.length w - 2))
               else if Str_util.starts_with ~prefix:"dll" w then Some (String.sub w 3 (String.length w - 3))
               else None)
        |> List.filter (fun n ->
               not (List.mem n [ "m"; "c"; "dl"; "rt"; "pthread" ] || List.mem n Deps.compiler_libs || List.mem_assoc n runtime_libs))
        |> List.sort_uniq compare

(* Their wasm archives, compiled as position-independent code (as all the
   C of the sysroot, Toolchain.compile_flags), linked into the plugin:
   built when missing, as for a program. *)
let plugin_archives input =
  let dirs = [ Filename.dirname input; Env.sysroot_file "lib" ] in
  cma_c_libs input
  |> List.filter_map (fun n ->
         let found () = Deps.find_lib dirs n in
         match found () with
         | Some a -> Some a
         | None -> (
             (match Deps.owner_of_dll n with
             | Some pkg ->
                 Env.log "lib%s.a missing, building it from opam package %s" n pkg;
                 Deps.obtain pkg n
             | None -> ( match Deps.lib_recipe n with Some r -> Deps.install_recipe r | None -> ()));
             match found () with
             | Some a -> Some a
             | None ->
                 Env.log "note: %s asks for -l%s, no wasm lib%s.a found: ignored" (Filename.basename input) n n;
                 None))

(* FILE.cma or FILE.cmo -> an emscripten side module, loaded by a program
   linked with --dynlink (Emcc_dynlink): c_of_ocaml compiles it to C that
   finds the compilation units of the program by name, compiled as
   position-independent code.  With [main] (the program's OUT.js or
   OUT.wasm), the symbols the plugin imports are checked against those the
   program exports. *)
let plugin ?effects ~input ~output ~main ~opt () =
  if not (Env.toolchain_ready ()) then
    Env.fail "no wasm runtime in %s, run `ocaml-emcc setup` first" (Env.sysroot ());
  check_compiled ();
  if not (Filename.check_suffix input ".cma" || Filename.check_suffix input ".cmo") then
    Env.fail "plugin: %s is not a .cma or .cmo file" input;
  if not (Sys.file_exists input) then Env.fail "plugin: %s: no such file" input;
  (* the program's exports, and the effects of the program: a plugin is
     compiled as the program was *)
  let main_wasm = Option.map (fun m -> if Filename.check_suffix m ".js" then Filename.chop_suffix m ".js" ^ ".wasm" else m) main in
  let main_exports = Option.map Wasm.exports main_wasm in
  let effects =
    match (effects, main_exports) with
    | Some e, _ -> Some e
    | None, Some l when List.mem "ocaml_emcc_double_translation" l ->
        Env.log "the program is compiled with effects (double translation): so is the plugin";
        Some "double-translation"
    | None, _ -> None
  in
  let emcc = Env.emcc () in
  let out_dir = Filename.dirname output in
  let base = Filename.remove_extension (Filename.basename output) in
  let work = Filename.concat out_dir ("." ^ base ^ ".ocaml-emcc") in
  mkdir_p work;
  let cooc = c_of_ocaml () in
  let support = Filename.concat work "c_of_ocaml" in
  mkdir_p support;
  Env.run_exn cooc [ "--runtime-files"; support ];
  let c_dir = Filename.concat work (base ^ ".c.d") in
  Env.log "compiling %s to C (c_of_ocaml)" (Filename.basename input);
  let word_size = if !Env.target = "wasm64" then [ "--word-size"; "64" ] else [] in
  (* the locations of backtraces, when compiled with -g *)
  let effects = match effects with Some e -> [ "--effects"; e ] | None -> [] in
  Env.run_exn cooc (word_size @ effects @ [ "--debug-info"; input; "--split"; c_dir ]);
  let parts =
    Sys.readdir c_dir |> Array.to_list
    |> List.filter (fun f -> Filename.check_suffix f ".c")
    |> List.sort compare
    |> List.map (Filename.concat c_dir)
  in
  let flags =
    Env.manifest_flags "cflags"
    @ [ opt; "-fPIC"; "-mtail-call"; "-I" ^ support; "-I" ^ Env.sysroot_file "lib/ocaml" ]
    @ [ "-Wno-incompatible-function-pointer-types" ]
  in
  let objs =
    List.map
      (fun c ->
        let o = Filename.chop_suffix c ".c" ^ ".o" in
        Env.run_exn emcc (flags @ [ "-c"; c; "-o"; o ]);
        o)
      parts
  in
  let archives = plugin_archives input in
  Env.log "linking the plugin %s%s" output
    (if archives = [] then "" else " (with " ^ String.concat " " (List.map Filename.basename archives) ^ ")");
  Env.run_exn emcc (Env.manifest_flags "ldflags" @ [ opt; "-sSIDE_MODULE=1" ] @ objs @ archives @ [ "-o"; output ]);
  match (main_wasm, main_exports) with
  | None, _ | _, None -> ()
  | Some wasm, Some exports -> (
      (* (or by the plugin itself: the GOT entries of its own functions
         whose address it takes, its C) *)
      let exported = Hashtbl.create 4096 in
      List.iter (fun s -> Hashtbl.replace exported s ()) (exports @ Wasm.exports output);
      let missing =
        Wasm.imports output
        |> List.filter_map (fun (m, f) ->
               if (m = "env" || m = "GOT.mem" || m = "GOT.func") && not (Str_util.starts_with ~prefix:"__" f || f = "memory")
                  && not (Hashtbl.mem exported f)
               then Some f
               else None)
        |> List.sort_uniq compare
      in
      match missing with
      | [] -> Env.log "%s: every symbol it imports is exported by %s" output wasm
      | l ->
          Env.fail
            "%s imports %d symbol(s) that %s does not export: %s\n\
            \  The C a plugin calls is in the plugin (the libraries its .cma names) or in the\n\
            \  program, linked with --compiled --dynlink (and -linkall)." output (List.length l) wasm (String.concat " " l))
