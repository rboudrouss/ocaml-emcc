(* Final link: bytecode + wasm runtime + static stubs -> emscripten module.

   1. the DLLS/DLPT sections are dropped from the bytecode (no dlopen),
   2. a primitive table is generated from the PRIM section: only the
      primitives the program uses are referenced, so wasm-ld can drop the
      rest of the runtime and of the stub libraries,
   3. each stub DLL dll<x> is replaced by the static archive lib<x>.a,
      except js_of_ocaml's, whose primitives are share/runtime/jsoo.c's
      (with the emscripten library jsoo.js), as are those of --js-file,
   4. emcc links everything with main.c, the bytecode being embedded in the
      virtual FS (or preloaded, or read from the real FS under node), or,
      for a standalone OUT.wasm, linked in as C arrays (Embed).

   By default (compiled), the bytecode is compiled to C by c_of_ocaml
   instead of being interpreted (--interpreted): 1, 2 and main.c are
   replaced by the generated C and its runtime support (see
   [compile_to_c]). *)

type mode =
  | Embed  (** bytecode inside the .wasm/.js (MEMFS) *)
  | Preload  (** bytecode in a separate .data file (MEMFS) *)
  | Node_rawfs  (** node only: real file system, .bc next to the .js *)

type opts = {
  bc : string;
  output : string;
  lib_dirs : string list;
  libs : string list;  (** extra archives / -l flags *)
  emcc_flags : string list;
  mode : mode;
  opt : string;
  stack_size : string;
  auto_deps : bool;
  check : bool;
  wasi : bool;  (** OUT.wasm for a WASI host (share/runtime/wasi.c) *)
  wasix : bool;  (** wasi, with WASIX's sockets (wasmer, share/runtime/wasix.c) *)
  compiled : bool;  (** compiled to C by c_of_ocaml rather than interpreted *)
  missing_prims : bool;  (** primitives no library defines raise Failure (else: link error) *)
  js_files : string list;  (** JavaScript files implementing primitives *)
  dynlink : bool;  (** compiled: a main module loading plugins (Emcc_dynlink) *)
  effects : string option;  (** compiled: c_of_ocaml's --effects *)
  threads : bool;  (** Thread.create and Domain.spawn start threads (shared memory) *)
}

(* C prototype of a primitive as the interpreter calls it. *)
let call_proto arity =
  match arity with
  | -1 -> "value *, int"
  | k -> String.concat ", " (List.init k (fun _ -> "value"))

let adapter_name p = "ocaml_emcc_adapt__" ^ p

(* The table of primitives.  Each primitive called by the bytecode is
   declared with the prototype of its call site.  A wasm call_indirect traps
   on any signature mismatch, where native code silently ignores extra
   arguments: the stubs whose definition does not match go through an
   adapter, see [mismatches] and [adapters_c], and wasm-ld reports those
   left. *)
let prims_c ~arities ~adapted prims =
  let b = Buffer.create 4096 in
  let pr fmt = Printf.bprintf b fmt in
  pr "/* Generated by ocaml-emcc: primitives used by the bytecode. */\n";
  pr "#include <stdint.h>\ntypedef intptr_t value;\ntypedef value (*c_primitive)();\n\n";
  let target p = if List.mem_assoc p adapted then adapter_name p else p in
  List.iteri
    (fun i p ->
      match Hashtbl.find_opt arities i with
      | Some a -> pr "extern value %s(%s);\n" (target p) (call_proto a)
      | None -> pr "extern value %s();\n" p)
    prims;
  pr "\nc_primitive caml_builtin_cprim[] = {\n";
  List.iter (fun p -> pr "  (c_primitive) %s,\n" (target p)) prims;
  pr "  0 };\n\nconst char * caml_names_of_builtin_cprim[] = {\n";
  List.iter (fun p -> pr "  \"%s\",\n" p) prims;
  pr "  0 };\n";
  (* Never called (and dropped by wasm-ld): taking an address does not make
     wasm-ld compare signatures, a direct call does. *)
  pr "\nvoid ocaml_emcc_signature_check(void) {\n";
  List.iteri
    (fun i p ->
      match Hashtbl.find_opt arities i with
      | Some -1 -> pr "  %s((value *)0, 0);\n" (target p)
      | Some k -> pr "  %s(%s);\n" (target p) (String.concat ", " (List.init k (fun _ -> "0")))
      | None -> ())
    prims;
  pr "}\n";
  Buffer.contents b

(* The signature of a primitive's call site, see [call_proto]. *)
let call_signature arity =
  let v = if !Env.target = "wasm64" then "i64" else "i32" in
  let params = match arity with -1 -> [ v; "i32" ] | k -> List.init k (fun _ -> v) in
  { Wasm.params; results = [ v ] }

(* The signatures of the primitives as the libraries define them, read
   from their objects, in link order: the first definition is the one
   wasm-ld links (it takes an archive member for a symbol still undefined,
   and the call sites come first).  Objects it cannot read (LTO bitcode)
   are skipped: wasm-ld then reports their mismatches itself. *)
let definitions ~prims files =
  let wanted = Hashtbl.create 256 and found = Hashtbl.create 256 in
  List.iter (fun p -> Hashtbl.replace wanted p ()) prims;
  let objects f =
    match Archive.members f with
    | Some m -> List.map (fun (n, c) -> (Printf.sprintf "%s(%s)" f n, c)) m
    | None -> ( match Compat.read_file f with c -> [ (f, c) ] | exception Sys_error _ -> [])
  in
  List.iter
    (fun f ->
      List.iter
        (fun (what, c) ->
          if Str_util.starts_with ~prefix:"\000asm" c then
            match Wasm.functions ~what c with
            | exception Failure e -> Env.log "note: %s, the signatures of its stubs are not checked" e
            | syms ->
                List.iter
                  (fun (s : Wasm.symbol) ->
                    if s.defined && (not s.local) && Hashtbl.mem wanted s.name && not (Hashtbl.mem found s.name) then
                      Hashtbl.replace found s.name s.signature)
                  syms)
        (objects f))
    files;
  found

(* The primitives whose definition differs from their call site (a direct
   call of which wasm-ld would replace with a trap), with the signature of
   the definition. *)
let mismatches ~arities ~prims files =
  let defs = definitions ~prims files in
  List.concat
    (List.mapi
       (fun i p ->
         match (Hashtbl.find_opt arities i, Hashtbl.find_opt defs p) with
         | Some a, Some sg when sg <> call_signature a -> [ (p, sg) ]
         | _ -> [])
       prims)

(* Adapters: the call-site signature on the outside, the real signature of
   the stub on the inside.  Extra arguments are dropped (what native code
   does implicitly), missing ones are passed as unit. *)
let adapters_c ~arities ~prims adapted =
  let b = Buffer.create 1024 in
  let pr fmt = Printf.bprintf b fmt in
  pr "/* Generated by ocaml-emcc: signature adapters for mismatched stubs. */\n";
  pr "#include <stdint.h>\ntypedef intptr_t value;\n\n";
  let index p =
    let rec go i = function [] -> -1 | x :: r -> if x = p then i else go (i + 1) r in
    go 0 prims
  in
  let ctype = function "f64" -> "double" | "f32" -> "float" | "i32" -> "int32_t" | _ -> "value" in
  List.iter
    (fun (p, (sg : Wasm.signature)) ->
      let params = sg.params and ret = match sg.results with [] -> "void" | t :: _ -> t in
      let arity = Option.value (Hashtbl.find_opt arities (index p)) ~default:1 in
      let decl_params = if params = [] then "void" else String.concat ", " (List.map ctype params) in
      let ret_t = if ret = "void" then "void" else ctype ret in
      pr "extern %s %s(%s);\n" ret_t p decl_params;
      let outer = List.init (if arity < 0 then 2 else arity) (fun i -> Printf.sprintf "a%d" i) in
      let outer_decl =
        if arity < 0 then "value *a0, int a1"
        else if arity = 0 then "void"
        else String.concat ", " (List.map (fun a -> "value " ^ a) outer)
      in
      let args =
        List.mapi
          (fun i t ->
            let a = if i < List.length outer then List.nth outer i else "1 /* Val_unit */" in
            Printf.sprintf "(%s)%s" (ctype t) (if arity < 0 && i = 0 then "(intptr_t)" ^ a else a))
          params
      in
      pr "value %s(%s) {\n" (adapter_name p) outer_decl;
      List.iter (fun a -> pr "  (void)%s;\n" a) outer;
      if ret = "void" then pr "  %s(%s);\n  return 1; /* Val_unit */\n" p (String.concat ", " args)
      else pr "  return (value)%s(%s);\n" p (String.concat ", " args);
      pr "}\n\n")
    adapted;
  Buffer.contents b

(* Stubs for the primitives no linked library defines (wasm-ld's undefined
   symbols), with the prototype of their call site: they raise Failure when
   called, as with js_of_ocaml, and a program that never calls them runs. *)
let missing_c ~arities ~prims names =
  let b = Buffer.create 1024 in
  let pr fmt = Printf.bprintf b fmt in
  pr "/* Generated by ocaml-emcc: primitives no linked library defines. */\n";
  pr "#include <caml/mlvalues.h>\n#include <caml/fail.h>\n\n";
  let arity p =
    let rec go i = function [] -> None | x :: r -> if x = p then Hashtbl.find_opt arities i else go (i + 1) r in
    Option.value (go 0 prims) ~default:1
  in
  List.iter
    (fun p ->
      let params, uses =
        match arity p with
        | -1 -> ("value *a0, int a1", [ "a0"; "a1" ])
        | 0 -> ("void", [])
        | k ->
            let a = List.init k (Printf.sprintf "a%d") in
            (String.concat ", " (List.map (( ^ ) "value ") a), a)
      in
      pr "value %s(%s) {\n" p params;
      List.iter (fun a -> pr "  (void)%s;\n" a) uses;
      pr "  caml_failwith(\"%s not implemented\");\n}\n\n" p)
    names;
  Buffer.contents b

(* The names of wasm-ld's (and emcc's) "undefined symbol: NAME" errors *)
let undefined_symbols err =
  let marker = "undefined symbol: " in
  String.split_on_char '\n' err
  |> List.filter_map (fun l ->
         match Str_util.find l marker with
         | Some j -> (
             let r = String.sub l (j + String.length marker) (String.length l - j - String.length marker) in
             match Str_util.words r with n :: _ -> Some n | [] -> None)
         | None -> None)
  |> List.sort_uniq compare

let write_file = Compat.write_file

(* ------------------------------------------------------------ c_of_ocaml *)

let c_of_ocaml () =
  match Env.getenv_opt "OCAML_EMCC_C_OF_OCAML" with
  | Some p -> p
  | None -> (
      match Env.which "c_of_ocaml" with
      | Some p -> p
      | None ->
          Env.fail
            "compiled mode (the default): c_of_ocaml not found in PATH (or set $OCAML_EMCC_C_OF_OCAML).\n\
            \  It is built from https://github.com/rboudrouss/C_of_ocaml (see ocaml-emcc's README).\n\
            \  --interpreted runs the bytecode on the interpreter instead.")

(* The C code generated by c_of_ocaml supports the runtimes of OCaml 4.14
   and 5, on wasm32 and wasm64. *)
let compiled_supported () =
  match Option.map (fun v -> Scanf.sscanf v "%d.%d" (fun a b -> (a, b))) (Env.manifest "ocaml_version") with
  | Some v when v < (4, 14) -> false
  | _ -> true

let check_compiled () =
  if not (compiled_supported ()) then
    Env.fail "compiled mode: needs OCaml 4.14 or later (the runtime support of c_of_ocaml); --interpreted runs the bytecode on the interpreter"

(* --threads: emcc's -pthread, the memory shared between the threads.
   The C code of the sysroot is always compiled for it (Toolchain): a
   sysroot set up before was not, and a shared memory refuses its objects.
   A standalone module has threads with WASI only (wasi-threads), emscripten
   starts its threads from the JavaScript glue. *)
let check_threads ~standalone (o : opts) =
  (match Stamp.read "ocaml" with
  | Some fields when Stamp.field "abi" fields = Some Toolchain.abi -> ()
  | _ -> Env.fail "--threads: the wasm runtime of %s was not built for threads (-pthread), run `ocaml-emcc setup` again" (Env.sysroot ()));
  if standalone && not o.wasi then
    Env.fail "--threads: a standalone %s has no threads (emscripten starts them from its JavaScript glue): link OUT.js, or use --wasi" o.output

(* The default maximum number of domains of a program with threads (with
   OCaml >= 5.3; OCAMLRUNPARAM's d= sets it): the runtime reserves their
   minor heaps at startup (4 MB each in wasm32, 2 MB in wasm64), which
   emscripten's mmap allocates *)
let max_domains = 8

(* The stack of a thread (pthread_create's default): the C stack of the
   interpreter, and that of compiled code's locals in memory *)
let thread_stack_size = 1024 * 1024

let threads_flags ~wasi ~proxy_to_pthread =
  [ "-pthread"; "-Wno-pthreads-mem-growth" ]
  @
  if wasi then
    (* wasi-threads: the host creates the shared memory the module imports,
       and wants it exported as well (wasmtime).  (The stack size is
       wasi_threads.c's.) *)
    [ "-Wl,--export-memory" ]
  else
    [ "-sDEFAULT_PTHREAD_STACK_SIZE=" ^ string_of_int thread_stack_size;
      "--js-library"; Filename.concat (Env.share ()) "runtime/threads.js" ]
    @
    if proxy_to_pthread then
      (* main runs in a pthread: the main thread of JavaScript stays free
         for what the other threads ask it (emscripten runs their system
         calls on files there: a write to stdout, the mmap of a new
         domain), and to start their workers.  A main thread waiting for
         another (a loop on a flag, Domain.join) or computing would
         otherwise never run them. *)
      [ "-sPROXY_TO_PTHREAD" ]
    else
      (* (js_of_ocaml: main on the page's thread) In a browser, workers
         started before main: a thread created by a program that then waits
         for it (join, a mutex) would never start, a new worker only loading
         once the main thread returns to its event loop.  8: OCaml's tick
         thread, and 7 others at the same time (-sPTHREAD_POOL_SIZE=N sets
         it).  None under node, which starts a worker at once: the pool
         would cost 200 ms and 140 MB at startup. *)
      [ "-sPTHREAD_POOL_SIZE=ENVIRONMENT_IS_NODE?0:8" ]

(* The primitives called by the generated C, with the arity of their call
   sites (-1: an array and its length), from its declarations
   "extern value NAME(value, value);". *)
let generated_prims c_file =
  let prefix = "extern value " in
  String.split_on_char '\n' (Compat.read_file c_file)
  |> List.filter_map (fun l ->
         if not (Str_util.starts_with ~prefix l) then None
         else
           match (String.index_opt l '(', String.rindex_opt l ')') with
           | Some i, Some j when i > String.length prefix && j > i ->
               let name = String.sub l (String.length prefix) (i - String.length prefix) in
               let params = String.trim (String.sub l (i + 1) (j - i - 1)) in
               let arity =
                 if params = "void" then 0
                 else if params = "value *, int" then -1
                 else List.length (String.split_on_char ',' params)
               in
               Some (name, arity)
           | _ -> None)

type compiled = {
  c_objs : string list;
  support_obj : string;
  cc : string list -> unit;
      (** compiles the generated C, with these extra flags, once the adapters
          are known *)
  c_prims : string list;
  c_arities : (int, int) Hashtbl.t;  (** arities by index in [c_prims] *)
}

(* PROG.bc -> PROG.c (c_of_ocaml), compiled with the runtime support of the
   generated code (camlc.h, camlc_runtime.c, which defines main), to be
   linked with libcamlrun.a: its interpreter is not used. *)
let compile_to_c ?(dynlink = false) ?effects ~emcc ~flags ~tail_calls ~work ~base ~bc bc_path =
  let cooc = c_of_ocaml () in
  let support = Filename.concat work "c_of_ocaml" in
  if not (Sys.file_exists support) then Unix.mkdir support 0o755;
  Env.run_exn cooc [ "--runtime-files"; support ];
  (* the C code in parts, compiled separately: DIR/part0.c (static data,
     tables, the declarations of the primitives), DIR/part1.c, ... *)
  let c_dir = Filename.concat work (base ^ ".c.d") in
  Env.log "compiling %s to C (c_of_ocaml)" (Filename.basename bc_path);
  (* backtraces when the bytecode has debug information (ocamlc -g) *)
  let debug = if Bytecode.section bc "DBUG" <> None then [ "--debug-info" ] else [] in
  let word_size = if !Env.target = "wasm64" then [ "--word-size"; "64" ] else [] in
  (* --dynlink: every compilation unit kept whole and registered by name,
     for plugins *)
  let dynlink = if dynlink then [ "--dynlink" ] else [] in
  let effects = match effects with Some e -> [ "--effects"; e ] | None -> [] in
  Env.run_exn cooc (debug @ word_size @ dynlink @ effects @ [ bc_path; "--split"; c_dir ]);
  let parts =
    Sys.readdir c_dir |> Array.to_list
    |> List.filter (fun f -> Filename.check_suffix f ".c")
    |> List.sort compare
    |> List.map (Filename.concat c_dir)
  in
  let c_objs = List.map (fun c -> Filename.chop_suffix c ".c" ^ ".o") parts in
  (* -mtail-call: tail calls of the generated code (return_call), unless
     asyncify, which does not support them, is used: tail calls are then
     plain calls (deep tail recursion may run out of stack) *)
  let flags =
    flags @ (if tail_calls then [ "-mtail-call" ] else [])
    @ [ "-I" ^ support; "-Wno-incompatible-function-pointer-types" ]
  in
  let support_obj = Filename.concat work "camlc_runtime.o" in
  Env.run_exn emcc (flags @ [ "-c"; Filename.concat support "camlc_runtime.c"; "-o"; support_obj ]);
  (* c_of_ocaml does not rewrite the parts left unchanged: they are not
     compiled again if their flags are the same (PART.flags) *)
  let cc extra =
    List.iter2
      (fun c o ->
        let args = flags @ extra @ [ "-c"; c; "-o"; o ] in
        let stamp = Filename.chop_suffix c ".c" ^ ".flags" in
        let key = String.concat "\n" (emcc :: args) in
        let up_to_date =
          Sys.file_exists o && Sys.file_exists stamp
          && (Unix.stat o).Unix.st_mtime >= (Unix.stat c).Unix.st_mtime
          && Compat.read_file stamp = key
        in
        if not up_to_date then (
          if Sys.file_exists stamp then Sys.remove stamp;
          Env.run_exn emcc args;
          write_file stamp key))
      parts c_objs
  in
  let prims = generated_prims (Filename.concat c_dir "part0.c") in
  let c_arities = Hashtbl.create 64 in
  List.iteri (fun i (_, a) -> Hashtbl.replace c_arities i a) prims;
  { c_objs; support_obj; cc; c_prims = List.map fst prims; c_arities }

let rec mkdir_p d =
  if not (Sys.file_exists d) then (
    mkdir_p (Filename.dirname d);
    Unix.mkdir d 0o755)

(* Global symbols defined by a set of archives/objects (llvm-nm), each file
   read once per link. *)
let file_symbols : (string, string list) Hashtbl.t = Hashtbl.create 16

let nm () =
  let emcc_dir = Filename.dirname (Env.emcc ()) in
  let cands = [ Filename.concat emcc_dir "../bin/llvm-nm"; Filename.concat emcc_dir "emnm" ] in
  match List.find_opt Sys.file_exists cands with Some n -> n | None -> "llvm-nm"

let defined_symbols files =
  let nm = nm () in
  let symbols f =
    match Hashtbl.find_opt file_symbols f with
    | Some l -> l
    | None ->
        let l =
          match Env.output_of nm [ "--defined-only"; "-g"; "-P"; "--quiet"; f ] with
          | None -> []
          | Some out ->
              String.split_on_char '\n' out
              |> List.filter_map (fun l -> match Str_util.words l with name :: _ :: _ -> Some name | _ -> None)
        in
        Hashtbl.replace file_symbols f l;
        l
  in
  let tbl = Hashtbl.create 4096 in
  List.iter (fun f -> List.iter (fun name -> Hashtbl.replace tbl name ()) (symbols f)) files;
  tbl

(* ctypes-foreign binds C functions by name at run time (dlsym).  The C
   symbols that string literals of the program name, and that the linked
   libraries or emscripten's libc define, are exported: share/runtime/dlsym.c
   finds them there.  A literal naming a libc function by chance only costs
   that function. *)
let is_c_ident s =
  let n = String.length s in
  let rec ok i = i >= n || ((match s.[i] with 'a' .. 'z' | 'A' .. 'Z' | '0' .. '9' | '_' -> true | _ -> false) && ok (i + 1)) in
  n > 0 && n <= 128 && (match s.[0] with 'a' .. 'z' | 'A' .. 'Z' | '_' -> true | _ -> false) && ok 1

(* (in emscripten's cache, $EM_CACHE if set; libstubs: the functions
   emscripten only has failing, getpwnam for opasswd) *)
let emscripten_system_libs () =
  let cache = match Env.getenv_opt "EM_CACHE" with Some d when d <> "" -> d | _ -> Filename.concat (Filename.dirname (Env.emcc ())) "cache" in
  let dir = List.fold_left Filename.concat cache [ "sysroot"; "lib"; !Env.target ^ "-emscripten" ] in
  List.filter Sys.file_exists (List.map (Filename.concat dir) [ "libc.a"; "libdlmalloc.a"; "libcompiler_rt.a"; "libstubs.a" ])

let foreign_exports ~archives bc =
  let syms = defined_symbols (archives @ emscripten_system_libs ()) in
  Bytecode.strings bc
  |> List.filter (fun s -> is_c_ident s && Hashtbl.mem syms s)
  |> List.sort_uniq compare

(* Stub libraries replaced by a file of share/runtime: js_of_ocaml's, whose
   stubs only abort outside JavaScript (jsoo.c), and ocaml-emcc.dynlink's
   (dynlink.c). *)
let runtime_libs = [ ("jsoo_runtime_stubs", "jsoo"); ("js_of_ocaml_stubs", "jsoo"); ("emcc_dynlink_stubs", "dynlink") ]

let uses_runtime name bc =
  List.exists (fun d -> List.assoc_opt (Bytecode.lib_of_dll d) runtime_libs = Some name) (Bytecode.dlls bc)

(* The global symbols each object of FILE (an archive, or an object)
   defines and those it needs, in order. *)
let objects_symbols f =
  match Env.output_of (nm ()) [ "-A"; "-g"; "-P"; "--quiet"; f ] with
  | None -> []
  | Some out ->
      let tbl = Hashtbl.create 64 and order = ref [] in
      String.split_on_char '\n' out
      |> List.iter (fun l ->
             (* "FILE[MEMBER]: SYM TYPE ..." or "FILE: SYM TYPE ..." *)
             let n = String.length f in
             if String.length l > n && String.sub l 0 n = f then
               let rest = String.sub l n (String.length l - n) in
               let member, rest =
                 if rest.[0] = '[' then
                   match Str_util.find rest "]: " with
                   | Some j -> (String.sub rest 1 (j - 1), String.sub rest (j + 3) (String.length rest - j - 3))
                   | None -> ("", "")
                 else if Str_util.starts_with ~prefix:": " rest then ("", String.sub rest 2 (String.length rest - 2))
                 else ("", "")
               in
               match Str_util.words rest with
               | sym :: ty :: _ ->
                   let d, u = match Hashtbl.find_opt tbl member with Some x -> x | None -> order := member :: !order; ([], []) in
                   let d, u =
                     match ty with "U" -> (d, sym :: u) | "w" | "v" -> (d, u) | _ -> (sym :: d, u)
                   in
                   Hashtbl.replace tbl member (d, u)
               | _ -> ());
      List.rev_map (fun m -> let d, u = Hashtbl.find tbl m in (m, d, u)) !order

(* The symbols defined by the members of ARCHIVES that a link of OBJECTS
   with them takes, as wasm-ld does: a member is linked when it defines a
   symbol still undefined, in any order of the archives. *)
let linked_symbols ~objects ~archives =
  let defined = Hashtbl.create 4096 and needed = Hashtbl.create 1024 in
  let add (d, u) =
    List.iter (fun s -> Hashtbl.replace defined s ()) d;
    List.iter (fun s -> if not (Hashtbl.mem defined s) then Hashtbl.replace needed s ()) u
  in
  List.iter (fun f -> List.iter (fun (_, d, u) -> add (d, u)) (objects_symbols f)) objects;
  let members = Array.of_list (Compat.concat_map objects_symbols archives) in
  let linked = Array.make (Array.length members) false in
  let rec fix () =
    let changed = ref false in
    Array.iteri
      (fun i (_, d, u) ->
        if (not linked.(i)) && List.exists (fun s -> Hashtbl.mem needed s && not (Hashtbl.mem defined s)) d then (
          linked.(i) <- true;
          changed := true;
          add (d, u)))
      members;
    if !changed then fix ()
  in
  fix ();
  let acc = ref [] in
  Array.iteri (fun i (_, d, _) -> if linked.(i) then acc := d @ !acc) members;
  !acc

(* C functions the code of a plugin may call directly, exported by a main
   module even when it does not use them itself *)
let plugin_libc =
  [ "malloc"; "calloc"; "realloc"; "free"; "memcpy"; "memmove"; "memset"; "memcmp"; "strlen"; "strcmp";
    "fmod"; "pow"; "exp"; "log"; "log10"; "floor"; "ceil"; "round"; "trunc"; "sqrt"; "sin"; "cos"; "tan";
    "atan"; "atan2"; "fabs"; "ldexp"; "frexp"; "expm1"; "log1p" ]

(* The symbols a main module (--dynlink) exports for its plugins: those its
   runtime support (EXPORTED objects) and the members of the archives it
   links define, and plugin_libc. The generated C of the program is not
   exported: plugins find its compilation units by name. *)
let main_exports ~objects ~exported ~archives =
  let syms = linked_symbols ~objects ~archives @ Hashtbl.fold (fun s () acc -> s :: acc) (defined_symbols exported) [] in
  List.sort_uniq compare (plugin_libc @ List.filter (fun s -> not (Str_util.starts_with ~prefix:"__" s)) syms)

(* Resolve every stub DLL to an archive, building missing ones if asked. *)
let resolve_libs ~extra_dirs ~auto_deps ~bc_path bc =
  Bytecode.dlls bc
  |> List.map Bytecode.lib_of_dll
  |> List.filter (fun n -> not (List.mem_assoc n runtime_libs))
  |> List.map (fun name ->
         let rec go first =
           match Deps.resolve ~extra_dirs ~bc_path bc name with
           | Deps.Found f -> (
               match Deps.stale name f with
               | Some (pkg, why) when auto_deps && first ->
                   Env.log "lib%s.a was built %s, rebuilding it" name why;
                   Deps.obtain pkg name;
                   go false
               | _ -> (name, f))
           | Deps.Missing (Some pkg) when auto_deps && first ->
               Env.log "lib%s.a missing, building it from opam package %s" name pkg;
               Deps.obtain pkg name;
               go false
           | Deps.Missing owner ->
               Env.fail "lib%s.a (wasm) not found%s.\n  Try: ocaml-emcc deps %s" name
                 (match owner with Some p -> " (provided by opam package " ^ p ^ ")" | None -> "")
                 bc_path
           | Deps.Local _ ->
               Env.fail
                 "lib%s.a (wasm) not found.  These look like the project's own stubs: build them with\n\
                 \  `ocaml-emcc dune` (dune build -x <target>), or use `ocaml-emcc build`, or pass -L <dir>." name
         in
         go true)

(* The -l flags of the linked libraries (dune's c_library_flags), recorded
   by the toolchain's ocamlc in meta/cclibs/<md5 of PROG.bc>: each -lX
   becomes the wasm libX.a if there is one.  Host flags (-L, -Wl,-rpath...)
   are dropped, so are the libraries emcc provides (libc, libm...), and
   -lstdc++ links as C++.  A library built with `ocamlmklib -custom`
   (stb_image) forces a custom link: its stubs are only named here, not in
   the DLLS section, and are obtained like those (when the opam package
   installed a dllX.so as well). *)
let cclib_flags ~auto_deps ~dirs bc_path =
  let file = Env.sysroot_file (Filename.concat "meta/cclibs" (Digest.to_hex (Digest.file bc_path))) in
  if not (Sys.file_exists file) then []
  else
    let seen = Hashtbl.create 16 in
    (* `-l X` as well as `-lX` (raylib: -cclib "-l GL") *)
    let rec join = function "-l" :: x :: l -> ("-l" ^ x) :: join l | x :: l -> x :: join l | [] -> [] in
    join (Str_util.words (String.map (fun c -> if c = '\n' || c = '\t' then ' ' else c) (Compat.read_file file)))
    |> Compat.concat_map (fun f ->
           if Hashtbl.mem seen f then []
           else (
             Hashtbl.add seen f ();
             if not (Str_util.starts_with ~prefix:"-l" f) then []
             else
               let n = String.sub f 2 (String.length f - 2) in
               match n with
               | "stdc++" | "c++" -> [ "-sDEFAULT_TO_CXX=1" ]
               | "m" | "c" | "dl" | "rt" | "pthread" -> []
               | n when List.mem_assoc n runtime_libs -> []
               | _ -> (
                   (* with the flags the library itself needs (libffi: -sALLOW_TABLE_GROWTH) *)
                   let found () = Option.map (fun a -> a :: Deps.link_flags n) (Deps.find_lib dirs n) in
                   match found () with
                   | Some l -> l
                   | None -> (
                       let built =
                         if not auto_deps then None
                         else
                           match Deps.owner_of_dll n with
                           | Some pkg ->
                               Env.log "lib%s.a missing (-l%s), building it from opam package %s" n n pkg;
                               Deps.obtain pkg n;
                               found ()
                           | None -> (
                               (* a C library (argon2, bound with ctypes-foreign) *)
                               match Deps.lib_recipe n with
                               | Some r ->
                                   Env.log "lib%s.a missing (-l%s), building the %s recipe" n n r;
                                   Deps.install_recipe r;
                                   found ()
                               | None -> None)
                       in
                       match built with
                       | Some l -> l
                       | None ->
                           Env.log "note: %s asks for -l%s, no wasm lib%s.a found: ignored" (Filename.basename bc_path) n n;
                           []))))

(* wasm32 runs 64-bit bytecode with 31-bit ints: report the literals that do
   not fit (the runtime wraps them when it loads the DATA section, see the
   `ocaml` recipe).  Arithmetic overflowing 31 bits cannot be detected. *)
let literals_report bc =
  match Bytecode.large_literals bc with
  | Bytecode.Unknown why -> `Unknown why
  | Bytecode.Found l -> (
      match List.sort_uniq compare (List.filter (fun n -> not (Bytecode.fits_31 n)) l) with
      | [] -> `Ok
      | l -> `Large l)

let show_literals l =
  let shown = Compat.filteri (fun i _ -> i < 8) l in
  String.concat ", " (List.map Int64.to_string shown) ^ if List.length l > 8 then ", ..." else ""

let warn_literals bc =
  match literals_report bc with
  | `Ok -> ()
  | `Unknown why -> Env.log "note: could not check integer literals (%s)" why
  | `Large l ->
      Env.log
        "warning: %d integer literal(s) do not fit in 31 bits (%s).\n\
        \  On wasm32 they are wrapped to 31 bits when the program starts, as 32-bit OCaml\n\
        \  would: fine for code only used on 32-bit platforms (Sys.word_size = 32), wrong\n\
        \  otherwise.  Use --target wasm64 if the program needs them."
        (List.length l) (show_literals l)

(* The bytecode must come from the compiler the runtime was built from. *)
let check_magic ~bc_path (bc : Bytecode.t) =
  let ocamlc = Filename.concat (Env.host_bin ()) "ocamlc" in
  match Env.output_of ocamlc [ "-config-var"; "exec_magic_number" ] with
  | Some m when m <> bc.Bytecode.magic ->
      Env.fail "%s was produced by another OCaml version (%s, this switch expects %s, OCaml %s).\n\
                \  Rebuild it with this switch, or use --switch." bc_path bc.Bytecode.magic m
        (Option.value (Env.manifest "ocaml_version") ~default:"?")
  | _ -> ()

(* wasm32 programs that may address more than 2GB get their exports returning
   pointers wrapped in JS (unsigned conversion): dlsym needs the wasm
   functions themselves for the function table. *)
let keep_raw_exports js =
  if Filename.check_suffix js ".js" && Sys.file_exists js then
    let s = Compat.read_file js in
    let pat = "wasmExports=applySignatureConversions(wasmExports)" in
    match Str_util.find s pat with
    | None -> ()
    | Some i ->
        let s =
          String.sub s 0 i ^ "Module[\"ocamlEmccRawExports\"]=wasmExports," ^ String.sub s i (String.length s - i)
        in
        write_file js s

(* dynlink.js: the names of the thread-local variables the program
   exports, read from its dylink.0 section once linked *)
let tls_exports_for_plugins js =
  let wasm = Filename.remove_extension js ^ ".wasm" in
  if Filename.check_suffix js ".js" && Sys.file_exists js && Sys.file_exists wasm then (
    let names = String.concat "," (List.map (Printf.sprintf "%S") (Wasm.tls_exports wasm)) in
    let s = Compat.read_file js in
    let s =
      List.fold_left
        (fun s pat ->
          match Str_util.find s pat with
          | Some i -> String.sub s 0 i ^ names ^ String.sub s (i + String.length pat) (String.length s - i - String.length pat)
          | None -> s)
        s [ "\"__OCAML_EMCC_TLS_EXPORTS__\""; "'__OCAML_EMCC_TLS_EXPORTS__'" ]
    in
    write_file js s)

(* Compiles share/runtime/NAME.c, whose functions stand in for libc or
   emscripten ones.  Those the program's libraries define as well are
   renamed out of the way (and dropped by wasm-ld), so that theirs are
   linked: a weak definition is not enough, wasm-ld does not take an
   archive member for a symbol that is already defined. *)
let runtime_object ~emcc ~flags ~lib_syms ~work ?(defs = []) name =
  let src = Filename.concat (Env.share ()) ("runtime/" ^ name ^ ".c") in
  let obj = Filename.concat work (name ^ ".o") in
  let cc overrides = Env.run_exn emcc (flags @ defs @ overrides @ [ "-c"; src; "-o"; obj ]) in
  cc [];
  Hashtbl.remove file_symbols obj;
  let theirs =
    Hashtbl.fold (fun sym () acc -> if Hashtbl.mem (Lazy.force lib_syms) sym then sym :: acc else acc) (defined_symbols [ obj ]) []
    |> List.sort compare
  in
  if theirs <> [] then (
    Env.log "%s: defined by the program's libraries, used instead of ocaml-emcc's (%s.c)" (String.concat " " theirs) name;
    cc (List.map (fun sym -> Printf.sprintf "-D%s=ocaml_emcc_overridden_%s" sym sym) theirs));
  obj

(* The host of a standalone module provides its imports: the WASI ones,
   and with emscripten's glue, emscripten's JavaScript functions (env). *)
let report_imports ~wasi ~wasix ~threads output =
  match Wasm.imports output with
  | exception Failure e -> Env.log "note: could not read the imports of %s (%s)" output e
  | imports -> (
      (* (threads: the shared memory, wasi-threads) *)
      let threads_import = function "env", "memory" | "wasi", "thread-spawn" -> threads | _ -> false in
      let others =
        List.filter (fun (m, f) -> m <> "wasi_snapshot_preview1" && not (threads_import (m, f) || (wasix && m = "wasix_32v1"))) imports
      in
      let names l =
        let shown = Compat.filteri (fun i _ -> i < 12) l in
        String.concat " " (List.map (fun (m, f) -> m ^ "." ^ f) shown) ^ if List.length l > 12 then " ..." else ""
      in
      match others with
      | [] -> if wasi then Env.log "%s: WASI module (%d WASI imports)" output (List.length imports)
      | l when wasi ->
          Env.log
            "warning: %s imports %d function(s) besides WASI: %s\n\
            \  A C library calls functions emscripten implements in JavaScript, which a WASI host\n\
            \  does not have (wasmtime: -W unknown-imports-trap=y runs it until one is called)."
            output (List.length l) (names l)
      | l ->
          Env.log
            "note: %s imports %d emscripten function(s) (%s): it needs a host providing them.\n\
            \  --wasi replaces them with WASI calls (a module for wasmtime, node:wasi...)."
            output (List.length l) (names l))

(* -sINITIAL_HEAP (emscripten >= 3.1.55): with MAXIMUM_MEMORY given,
   emscripten fixes the initial memory at 16 MB instead (INITIAL_MEMORY),
   which the static data alone can exceed (the interpreter's embedded
   bytecode of a big program: 72 MB for core with -linkall).  wasm-ld then
   adds the heap to the static data and the stack.  Not when the user's
   flags size the memory. *)
let initial_heap ~threads ~bc_size user_flags =
  let sized = List.exists (fun f -> List.exists (fun k -> Str_util.find f k <> None) [ "INITIAL_MEMORY"; "INITIAL_HEAP"; "IMPORTED_MEMORY" ]) user_flags in
  let version = List.map int_of_string_opt (String.split_on_char '.' (Lazy.force Toolchain.emcc_version)) in
  let recent = match version with Some a :: Some b :: Some c :: _ -> compare (a, b, c) (3, 1, 55) >= 0 | _ -> false in
  (* (threads: the memory is imported, which INITIAL_HEAP refuses: 64 MB
     for the minor heaps of the domains, allocated at startup, and the
     heap, plus room for static data as big as the bytecode, twice) *)
  let mb = 1024 * 1024 in
  if sized then []
  else if threads then [ Printf.sprintf "-sINITIAL_MEMORY=%d" ((64 * mb) + ((2 * bc_size + mb - 1) / mb * mb)) ]
  else if recent then [ "-sINITIAL_HEAP=16777216" ]
  else []

(* The primitives a JavaScript file provides: its `//Provides: NAME`
   comments (as js_of_ocaml's runtime files) and its toplevel
   `function NAME(`. *)
let js_provides file =
  let ident s i =
    let n = String.length s in
    let rec stop j = if j < n && (match s.[j] with 'a' .. 'z' | 'A' .. 'Z' | '0' .. '9' | '_' | '$' -> true | _ -> false) then stop (j + 1) else j in
    let j = stop i in
    if j > i then Some (String.sub s i (j - i)) else None
  in
  let skip_spaces s i = let rec go i = if i < String.length s && (s.[i] = ' ' || s.[i] = '\t') then go (i + 1) else i in go i in
  String.split_on_char '\n' (Compat.read_file file)
  |> List.filter_map (fun l ->
         let t = String.trim l in
         let after p = if Str_util.starts_with ~prefix:p t then ident t (skip_spaces t (String.length p)) else None in
         match after "//Provides:" with
         | Some n -> Some n
         | None -> ( match after "// Provides:" with Some n -> Some n | None -> if Str_util.starts_with ~prefix:"function " l then after "function" else None))
  |> List.sort_uniq compare

(* Stubs for the primitives implemented in JavaScript, with the prototype of
   their call site: they call the function of the same name (jsoo.c). *)
let js_prims_c ~arity names =
  let b = Buffer.create 1024 in
  let pr fmt = Printf.bprintf b fmt in
  pr "/* Generated by ocaml-emcc: primitives implemented in JavaScript (--js-file). */\n";
  pr "#include <stdint.h>\ntypedef intptr_t value;\n";
  pr "extern value ocaml_emcc_js_prim(const char *name, int n, value *args);\n\n";
  List.iter
    (fun p ->
      match arity p with
      | -1 -> pr "value %s(value *argv, int argc) { return ocaml_emcc_js_prim(\"%s\", argc, argv); }\n" p p
      | 0 -> pr "value %s(void) { return ocaml_emcc_js_prim(\"%s\", 0, 0); }\n" p p
      | k ->
          let a = List.init k (Printf.sprintf "a%d") in
          pr "value %s(%s) {\n  value args[] = { %s };\n  return ocaml_emcc_js_prim(\"%s\", %d, args);\n}\n" p
            (String.concat ", " (List.map (( ^ ) "value ") a))
            (String.concat ", " a) p k)
    names;
  Buffer.contents b

let run o =
  if not (Env.toolchain_ready ()) then
    Env.fail "no wasm runtime in %s, run `ocaml-emcc setup` first" (Env.sysroot ());
  (* emcc's -pthread among the user's flags: the program's threads *)
  let o = if List.mem "-pthread" o.emcc_flags then { o with threads = true } else o in
  let emcc = Env.emcc () in
  let bc = Bytecode.parse o.bc in
  check_magic ~bc_path:o.bc bc;
  (* OUT.wasm alone: emcc's standalone mode, no JavaScript glue *)
  let standalone = Filename.check_suffix o.output ".wasm" in
  if o.wasi && not standalone then Env.fail "--wasi makes a WASI module: the output must be OUT.wasm (not %s)" o.output;
  if o.wasi && !Env.target = "wasm64" then
    Env.fail "--wasi: WASI (preview1) is 32-bit, no WASI host runs a wasm64 module.  Use --target wasm32.";
  if standalone && o.mode <> Embed then
    Env.fail "--preload and --node-fs need the JavaScript glue: not available for a standalone %s" o.output;
  if o.compiled then check_compiled ();
  if o.dynlink && not o.compiled then Env.fail "--dynlink: plugins need the compiled mode (not --interpreted)";
  if o.dynlink && standalone then Env.fail "--dynlink: plugins are loaded by the JavaScript glue: link OUT.js, not a standalone .wasm";
  if o.threads then check_threads ~standalone o;
  if !Env.target = "wasm32" then warn_literals bc;
  if o.auto_deps then (Layouts.prune (); ignore (Layouts.ensure bc));
  Layouts.warn ~bc_path:o.bc bc;
  let out_dir = Filename.dirname o.output in
  let base = Filename.remove_extension (Filename.basename o.output) in
  let work = Filename.concat out_dir ("." ^ base ^ ".ocaml-emcc") in
  mkdir_p work;
  (* 1. bytecode without DLLS/DLPT (a standalone module has it as C arrays,
     bytecode.c below) *)
  let bc_name = base ^ ".bc" in
  let bc_out =
    match o.mode with Node_rawfs -> Filename.concat out_dir bc_name | _ -> Filename.concat work bc_name
  in
  if not (standalone || o.compiled) then Bytecode.write ~drop:[ "DLLS"; "DLPT" ] bc bc_out;
  (* 2. primitive table *)
  let prims = Bytecode.primitives bc in
  let arities = Bytecode.call_arities bc in
  let prims_src = Filename.concat work "prims.c" in
  (* 3. libraries *)
  let libs = resolve_libs ~extra_dirs:o.lib_dirs ~auto_deps:o.auto_deps ~bc_path:o.bc bc in
  let camlrun = Env.sysroot_file "lib/libcamlrun.a" in
  let archives = List.map snd libs @ [ camlrun ] in
  (* the archives given with -l (paths, or -lX found in the lib dirs) *)
  let user_archives () =
    List.filter_map
      (fun l ->
        if Sys.file_exists l then Some l
        else if Str_util.starts_with ~prefix:"-l" l then
          Deps.find_lib (o.lib_dirs @ [ Env.sysroot_file "lib" ]) (String.sub l 2 (String.length l - 2))
        else None)
      (o.libs @ List.filter (Str_util.starts_with ~prefix:"-l") o.emcc_flags)
  in
  (* (and those of the runtime: -lzstd since OCaml 5.1) *)
  let flags_of_libs = Compat.concat_map Deps.link_flags (List.map fst libs @ [ "camlrun" ]) in
  let lib_dirs = Deps.search_dirs ~extra_dirs:o.lib_dirs ~bc_path:o.bc bc in
  let flags_of_libs = flags_of_libs @ cclib_flags ~auto_deps:o.auto_deps ~dirs:lib_dirs o.bc in
  (* (the program's link decides whether it has threads, not a library) *)
  let flags_of_libs = List.filter (( <> ) "-pthread") flags_of_libs in
  (* the archives of those flags: paths (c_library_flags) and -lX *)
  let flag_archives =
    List.filter_map
      (fun f ->
        if Str_util.starts_with ~prefix:"-l" f then Deps.find_lib lib_dirs (String.sub f 2 (String.length f - 2))
        else if Filename.check_suffix f ".a" && Sys.file_exists f then Some f
        else None)
      flags_of_libs
  in
  (* what the program's libraries define (not the runtime's) *)
  let lib_syms = lazy (defined_symbols (List.map snd libs @ user_archives () @ flag_archives)) in
  (* js_of_ocaml's primitives (share/runtime/jsoo.c), for its libraries and
     the primitives of the --js-file files *)
  List.iter (fun f -> if not (Sys.file_exists f) then Env.fail "--js-file %s: no such file" f) o.js_files;
  let js_provided = Compat.concat_map js_provides o.js_files in
  let jsoo = uses_runtime "jsoo" bc || o.js_files <> [] in
  if jsoo && standalone then
    Env.fail "%s: js_of_ocaml's primitives and --js-file need the JavaScript glue: link OUT.js, not a standalone .wasm"
      (if o.js_files <> [] then "--js-file" else o.bc);
  (* threads with the JavaScript glue: the program runs in a pthread,
     unless it needs the page (js_of_ocaml's primitives) *)
  let proxy_to_pthread = o.threads && (not o.wasi) && not jsoo in
  let jsoo_objs =
    lazy
      (if not jsoo then []
       else [ runtime_object ~emcc ~flags:(Env.manifest_flags "cflags" @ [ o.opt; "-I" ^ Env.sysroot_file "lib/ocaml" ]) ~lib_syms ~work "jsoo" ])
  in
  let dynlink_objs =
    lazy
      (if not (uses_runtime "dynlink" bc || o.dynlink) then []
       else
         [ runtime_object ~emcc ~lib_syms ~work "dynlink"
             ~flags:
               (Env.manifest_flags "cflags" @ [ o.opt; "-I" ^ Env.sysroot_file "lib/ocaml" ]
               @ (if o.dynlink then [ "-DOCAML_EMCC_DYNLINK" ] else [])
               @ if o.effects = Some "double-translation" then [ "-DOCAML_EMCC_DOUBLE_TRANSLATION" ] else []) ])
  in
  if o.check then (
    let syms = defined_symbols (archives @ user_archives () @ flag_archives @ Lazy.force jsoo_objs @ Lazy.force dynlink_objs) in
    let missing = List.filter (fun p -> not (Hashtbl.mem syms p || List.mem p js_provided)) prims in
    if missing <> [] then
      Env.log "warning: %d primitive(s) not defined by any linked library:\n  %s\n\
               (add the library providing them with -l/-L, or %s)"
        (List.length missing) (String.concat " " missing)
        (if o.missing_prims then "they raise Failure when called" else "link will fail"));
  let foreign =
    if not (List.mem "ctypes_dlsym" prims) then None
    else
      let names = foreign_exports ~archives:(archives @ user_archives () @ flag_archives) bc in
      Env.log "dlsym (ctypes-foreign): exporting %d C symbol(s) named in the program" (List.length names);
      Some names
  in
  (* 4. emcc *)
  let inc = [ "-I" ^ Env.sysroot_file "lib/ocaml"; "-I" ^ Env.sysroot_file "include" ] in
  let vfs_path = "/ocaml/" ^ bc_name in
  let main_def =
    match o.mode with
    | _ when standalone -> "-DOCAML_EMCC_EMBEDDED"
    | Node_rawfs -> "-DOCAML_EMCC_BYTECODE=0"
    | _ -> Printf.sprintf "-DOCAML_EMCC_BYTECODE=\"%s\"" vfs_path
  in
  let main_o = Filename.concat work "main.o" and prims_o = Filename.concat work "prims.o" in
  (* Same flags as the runtime (target, longjmp flavour...). *)
  let cflags = Env.manifest_flags "cflags" and ldflags = Env.manifest_flags "ldflags" in
  let compiled =
    if o.compiled then (
      (* JSPI (-sJSPI, or the older -sASYNCIFY=2) supports them, and takes
         precedence over asyncify *)
      let all = ldflags @ flags_of_libs @ o.emcc_flags in
      let jspi f =
        f = "-sJSPI" || f = "-sJSPI=1" || f = "-sASYNCIFY=2"
      in
      let asyncify f = Str_util.starts_with ~prefix:"-sASYNCIFY" f && f <> "-sASYNCIFY=0" in
      let tail_calls = List.exists jspi all || not (List.exists asyncify all) in
      if not tail_calls then Env.log "asyncify: compiled without wasm tail calls";
      Some (compile_to_c ~dynlink:o.dynlink ?effects:o.effects ~emcc ~flags:(cflags @ [ o.opt ] @ inc) ~tail_calls ~work ~base ~bc o.bc))
    else None
  in
  if compiled = None then
    Env.run_exn emcc (cflags @ [ o.opt; main_def ] @ inc @ [ "-c"; Filename.concat (Env.share ()) "runtime/main.c"; "-o"; main_o ]);
  let runtime_object = runtime_object ~emcc ~flags:(cflags @ [ o.opt ]) ~lib_syms ~work in
  let compat_o =
    runtime_object "compat" ~defs:[ Printf.sprintf "-DOCAML_EMCC_MAX_DOMAINS=%d" (if o.threads then max_domains else 1) ]
  in
  let foreign_objs, foreign_flags =
    match foreign with
    | None -> ([], [])
    | Some names ->
        let dlsym_o = runtime_object "dlsym" in
        ([ dlsym_o ], "-sALLOW_TABLE_GROWTH=1" :: List.map (fun n -> "-Wl,--export=" ^ n) names)
  in
  let wasi_objs () =
    if not o.wasi then []
    else
      runtime_object "wasi"
      :: (if o.wasix then [ runtime_object "wasix" ] else [])
      @ (if o.threads then [ runtime_object "wasi_threads" ~defs:[ "-DOCAML_EMCC_THREAD_STACK_SIZE=" ^ string_of_int thread_stack_size ] ]
          else [])
  in
  (* the main thread frees the workers of exited threads while blocked *)
  let threads_objs = if o.threads && not o.wasi then [ runtime_object "threads" ] else [] in
  let standalone_objs =
    if not standalone then []
    else if compiled <> None then wasi_objs ()
    else (
      let ocaml_major = Option.fold ~none:5 ~some:(fun v -> Scanf.sscanf v "%d" Fun.id) (Env.manifest "ocaml_version") in
      let src = Embed.write ~ocaml_major ~dir:work bc and bytecode_o = Filename.concat work "bytecode.o" in
      Env.run_exn emcc (cflags @ [ o.opt; "-Wno-c23-extensions"; "-c"; src; "-o"; bytecode_o ]);
      (* a runtime built before ocaml-emcc linked bytecode in as data *)
      if not (Hashtbl.mem (defined_symbols [ camlrun ]) "caml_emcc_debug_events") then
        Env.log
          "note: the wasm runtime of this switch predates standalone modules: backtraces have no\n\
          \  locations%s.  Rebuild it with `ocaml-emcc setup --force`."
          (if !Env.target = "wasm32" then ", and integer literals beyond 31 bits fail at startup" else "");
      bytecode_o :: wasi_objs ())
  in
  let cc_prims () =
    Env.run_exn emcc
      (cflags @ [ o.opt; "-std=gnu11"; "-Wno-incompatible-function-pointer-types"; "-Wno-deprecated-non-prototype"; "-c"; prims_src; "-o"; prims_o ])
  in
  let fs_flags =
    match o.mode with
    | _ when standalone -> []
    | (Embed | Preload) when compiled <> None -> []
    | Node_rawfs when compiled <> None ->
        let pre = Filename.concat work "pre.js" in
        write_file pre
          "// the environment of the node process, as for a native program\n\
           Module['preRun'] = [].concat(Module['preRun'] || [], function () { Object.assign(ENV, process.env); });\n";
        [ "-sNODERAWFS=1"; "-sENVIRONMENT=node"; "--pre-js"; pre ]
    | Embed -> [ "--embed-file"; bc_out ^ "@" ^ vfs_path ]
    | Preload -> [ "--preload-file"; bc_out ^ "@" ^ vfs_path ]
    | Node_rawfs ->
        let pre = Filename.concat work "pre.js" in
        write_file pre
          (Printf.sprintf
             "if (typeof __dirname !== 'undefined')\n\
             \  Module['thisProgram'] = require('path').join(__dirname, %S);\n\
              // the environment of the node process, as for a native program\n\
              Module['preRun'] = [].concat(Module['preRun'] || [], function () { Object.assign(ENV, process.env); });\n"
             bc_name);
        [ "-sNODERAWFS=1"; "-sENVIRONMENT=node"; "--pre-js"; pre ]
  in
  let defaults =
    ldflags
    @ [
      o.opt;
      "-sALLOW_MEMORY_GROWTH=1";
      (if !Env.target = "wasm64" then "-sMAXIMUM_MEMORY=16GB" else "-sMAXIMUM_MEMORY=4GB");
    ]
    @ initial_heap ~threads:o.threads ~bc_size:(Unix.stat o.bc).Unix.st_size o.emcc_flags
    @ [
      "-sSTACK_SIZE=" ^ o.stack_size;
      (* not allowed (implied) for a standalone .wasm *)
      (if standalone then "" else "-sEXIT_RUNTIME=1");
      "-sERROR_ON_UNDEFINED_SYMBOLS=1";
      (* C++ exceptions (sysroots set up before it was a target flag) *)
      "-fwasm-exceptions";
    ]
  in
  let defaults = List.filter (( <> ) "") defaults in
  (* the standard streams of node, as bytes (not for a standalone .wasm),
     and /etc/localtime (not with node's files) *)
  let defaults =
    if standalone then defaults else defaults @ [ "--pre-js"; Filename.concat (Env.share ()) "runtime/node_stdio.js" ]
  in
  let defaults =
    if standalone || o.mode = Node_rawfs then defaults
    else defaults @ [ "--pre-js"; Filename.concat (Env.share ()) "runtime/localtime.js" ]
  in
  (* compiled code runs on the wasm engine's stack: a large one under node.
     malloc and free are exported, as with the interpreter (whose file
     system needs them), for the JS code of the stubs (libffi...). *)
  let defaults =
    if standalone || compiled = None then defaults
    else
      defaults
      @ [ "--pre-js"; Filename.concat (Env.share ()) ("runtime/" ^ if proxy_to_pthread then "node_threads_stack.js" else "node_stack.js");
          "-sEXPORTED_FUNCTIONS=_main,_malloc,_free" ]
  in
  (* WASI: no emscripten imports at all (PURE_WASI: memory growth without
     telling JS), and the standard exception handling instructions
     (exnref), the only ones WASI hosts such as wasmtime implement:
     setjmp/longjmp (OCaml exceptions raised from C) use them, compiled in
     the legacy encoding emscripten defaults to. *)
  let defaults =
    if o.wasi then defaults @ [ "-sPURE_WASI=1"; "-sBINARYEN_EXTRA_PASSES=--translate-to-exnref,--emit-exnref" ]
    else defaults
  in
  let defaults = if o.threads then defaults @ threads_flags ~wasi:o.wasi ~proxy_to_pthread else defaults in
  let program_objs =
    match compiled with
    | Some c -> c.c_objs @ [ c.support_obj ]
    | None -> [ main_o; prims_o ]
  in
  (* the primitives of the --js-file files no library defines: stubs
     calling them, and their table (a JavaScript file run before the
     program, after them) *)
  let js_objs, js_flags =
    if not jsoo then ([], [])
    else
      let prims, arities = match compiled with Some c -> (c.c_prims, c.c_arities) | None -> (prims, arities) in
      let defined = defined_symbols (archives @ user_archives () @ flag_archives @ Lazy.force jsoo_objs) in
      let names = List.filter (fun p -> List.mem p js_provided && not (Hashtbl.mem defined p)) prims in
      let arity p =
        let rec go i = function [] -> 1 | x :: r -> if x = p then Option.value (Hashtbl.find_opt arities i) ~default:1 else go (i + 1) r in
        go 0 prims
      in
      let objs =
        if names = [] then []
        else (
          Env.log "%d primitive(s) implemented in JavaScript: %s" (List.length names) (String.concat " " names);
          let src = Filename.concat work "js_prims.c" and obj = Filename.concat work "js_prims.o" in
          write_file src (js_prims_c ~arity names);
          Env.run_exn emcc (cflags @ [ o.opt; "-c"; src; "-o"; obj ]);
          [ obj ])
      in
      let table = Filename.concat work "js_prims.js" in
      write_file table
        (Printf.sprintf "// Generated by ocaml-emcc: the functions and values of the --js-file files\nvar ocamlEmccJsPrims = {\n%s};\n"
           (String.concat ""
              (List.map (fun n -> Printf.sprintf "  %S: typeof %s == 'undefined' ? undefined : %s,\n" n n n) js_provided)));
      ( Lazy.force jsoo_objs @ objs,
        [ "--js-library"; Filename.concat (Env.share ()) "runtime/jsoo.js" ]
        @ Compat.concat_map (fun f -> [ "--pre-js"; f ]) o.js_files
        @ [ "--pre-js"; table ] )
  in
  (* Emcc_dynlink's primitives, and a main module exporting what plugins
     need (main_exports, computed before the link) *)
  let dynlink_objs = Lazy.force dynlink_objs in
  let exports_file = Filename.concat work "exports.json" in
  let dynlink_flags =
    if not o.dynlink then []
    else
      [ "-sMAIN_MODULE=2"; "-sEXPORTED_FUNCTIONS=@" ^ exports_file ]
      @ (* the thread-local variables of the program for its plugins
           (emscripten relocates them itself with threads) *)
      if o.threads then []
      else [ "--js-library"; Filename.concat (Env.share ()) "runtime/dynlink.js"; "-sDEFAULT_LIBRARY_FUNCS_TO_INCLUDE=$ocamlEmccTlsExports" ]
  in
  let defaults =
    if o.dynlink then List.filter (fun f -> not (Str_util.starts_with ~prefix:"-sEXPORTED_FUNCTIONS=" f)) defaults
    else defaults
  in
  let args ?(extra = []) ~output () =
    defaults @ fs_flags @ program_objs @ [ compat_o ] @ standalone_objs @ threads_objs @ foreign_objs @ js_objs @ dynlink_objs @ extra
    @ archives @ o.libs
    @ [ "-L" ^ Env.sysroot_file "lib" ]
    @ flags_of_libs @ [ "-lm" ] @ foreign_flags @ js_flags @ dynlink_flags @ o.emcc_flags @ [ "-o"; output ]
  in
  Env.log "linking %s (%d primitives, %d stub libraries%s)" o.output (List.length prims) (List.length libs)
    (if compiled <> None then ", compiled" else "");
  (* a program that may start threads, single-threaded (the bytecode of
     any OCaml 5 program has Domain.spawn's primitive, its standard library
     links Domain: compiled code only has the primitives it calls) *)
  let starts =
    match compiled with
    | Some c -> List.filter (fun p -> List.mem p c.c_prims) [ "caml_thread_new"; "caml_domain_spawn" ]
    | None -> List.filter (fun p -> List.mem p prims) [ "caml_thread_new" ]
  in
  if (not o.threads) && starts <> [] then
    Env.log "note: %s fail%s in a program linked without --threads (threads: yes in ocaml-emcc.conf)"
      (String.concat " and " (List.map (function "caml_thread_new" -> "Thread.create" | _ -> "Domain.spawn") starts))
      (if List.length starts = 1 then "s" else "");
  (* The primitives called, and the stubs whose C signature differs from
     the call site: called through an adapter. *)
  let prims, arities = match compiled with Some c -> (c.c_prims, c.c_arities) | None -> (prims, arities) in
  let adapted =
    mismatches ~arities ~prims
      ((compat_o :: standalone_objs) @ foreign_objs @ js_objs @ dynlink_objs @ archives @ user_archives () @ flag_archives)
  in
  let adapters =
    if adapted = [] then []
    else (
      Env.log "%d stub(s) with a C signature different from their OCaml arity, adapting: %s" (List.length adapted)
        (String.concat " " (List.map fst adapted));
      let adapters_src = Filename.concat work "adapters.c" and adapters_o = Filename.concat work "adapters.o" in
      write_file adapters_src (adapters_c ~arities ~prims adapted);
      Env.run_exn emcc (cflags @ [ o.opt; "-w"; "-c"; adapters_src; "-o"; adapters_o ]);
      [ adapters_o ])
  in
  (match compiled with
  | Some c ->
      (* the generated C calls the adapters instead *)
      c.cc (List.map (fun (p, _) -> Printf.sprintf "-D%s=%s" p (adapter_name p)) adapted)
  | None ->
      write_file prims_src (prims_c ~arities ~adapted prims);
      cc_prims ());
  if o.dynlink then (
    let support = match compiled with Some c -> [ c.support_obj ] | None -> [] in
    let exported = support @ [ compat_o ] @ js_objs @ dynlink_objs @ adapters in
    let exports =
      main_exports ~objects:(program_objs @ exported) ~exported
        ~archives:(archives @ user_archives () @ flag_archives @ emscripten_system_libs ())
    in
    Env.log "--dynlink: a main module exporting %d symbols for its plugins" (List.length exports);
    write_file exports_file
      ("[" ^ String.concat "," (List.map (fun s -> Printf.sprintf "%S" ("_" ^ s)) ("main" :: exports)) ^ "]\n"));
  let code, err = Env.run_capture_stderr emcc (args ~extra:adapters ~output:o.output ()) in
  (* undefined symbols that are all primitives of the program: stubs that
     raise Failure, and the link again *)
  let code, err =
    let undefined = if code = 0 || not o.missing_prims then [] else undefined_symbols err in
    let is_prim = Hashtbl.create 256 in
    List.iter (fun p -> Hashtbl.replace is_prim p ()) prims;
    if undefined = [] || not (List.for_all (Hashtbl.mem is_prim) undefined) then (code, err)
    else (
      Env.log "warning: %d primitive(s) not available in this build, they raise Failure when called: %s"
        (List.length undefined) (String.concat " " undefined);
      let missing_src = Filename.concat work "missing.c" and missing_o = Filename.concat work "missing.o" in
      write_file missing_src (missing_c ~arities ~prims undefined);
      Env.run_exn emcc (cflags @ [ o.opt ] @ inc @ [ "-c"; missing_src; "-o"; missing_o ]);
      Env.run_capture_stderr emcc (args ~extra:(adapters @ [ missing_o ]) ~output:o.output ()))
  in
  (* emcc's messages.  Mismatches left are calls between C functions that
     wasm-ld replaced with a trap: shown, with an explanation. *)
  let marker = "function signature mismatch: " in
  let traps =
    String.split_on_char '\n' err
    |> List.filter_map (fun l ->
           if l <> "" then prerr_endline l;
           match Str_util.find l marker with
           | Some j -> Some (String.trim (String.sub l (j + String.length marker) (String.length l - j - String.length marker)))
           | None -> None)
  in
  if traps <> [] then
    Env.log
      "warning: C function(s) called with a signature different from their definition: %s.\n\
      \  wasm-ld replaced those calls with a trap: the program stops with \"RuntimeError: unreachable\"\n\
      \  if it makes them.  Most likely a stub declares the function itself with other types\n\
      \  (int for long, which differ on wasm64)."
      (String.concat " " (List.sort_uniq compare traps));
  if code <> 0 then Env.fail "emcc failed (exit %d)" code;
  if foreign <> None then keep_raw_exports o.output;
  if o.dynlink && not o.threads then tls_exports_for_plugins o.output;
  if standalone then report_imports ~wasi:o.wasi ~wasix:o.wasix ~threads:o.threads o.output

